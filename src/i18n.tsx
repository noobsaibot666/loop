const localeMap: Record<Language, string> = {
  en: "en-US",
  pt: "pt-BR",
  es: "es-ES",
};

const I18nContext = createContext<I18nContextValue | null>(null);

function resolveLanguage(value: string | null): Language {
  if (value === "pt" || value === "es") return value;
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    return resolveLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));
  });

  useEffect(() => {
    if (typeof window === "undefined") return;
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const translate = (key: string, vars?: Record<string, string | number>) => {
      const template = dictionaries[language][key] || dictionaries.en[key] || key;
      if (!vars) return template;
      return Object.entries(vars).reduce((result, [name, replacement]) => {
        return result.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement));
      }, template);
    };

    return {
      language,
      setLanguage: setLanguageState,
      t: translate,
      formatDate: (value?: string | null) => {
        if (!value) return "--";
        const date = new Date(value);
        if (Number.isNaN(date.getTime())) return "--";
        return new Intl.DateTimeFormat(localeMap[language], {
          year: "numeric",
          month: "2-digit",
          day: "2-digit",
        }).format(date);
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}
